#!/usr/bin/env python3
"""Write the work-area save routines of the library modules.

An interrupt function that reaches a library routine with work areas at
fixed RAM addresses (lc_vm, lc_sqrt, rt_fdata, ...) must save and restore
the areas (--isr-save-workareas, docs/rom_hardware.md).  The data labels of
a library module are private, so each module with a work area exports one
label for its area, and a module of its own holds two public routines that
know the area:

    __wa_<block>     (in the module of the area) the first byte of the area
    __wasv_<block>   (in lc_wa_<block>.mac) push the area onto the stack; the
                     call returns with the area below the return point
    __wars_<block>   copy the area back and drop it from the stack

Both routines use IY for the return address (the prologue of an interrupt
function has saved IY) and change AF, BC, DE, HL.  The routines are modules
of their own, so a program that does not reference them does not link them:
the modules with a work area get no byte of code.  The label __wa_<block>
costs no byte either.  The joined files libc.mac and runtime.mac leave the
new label and the new modules out (the lines end in ;! and the first line of
a new module says CONCAT-SKIP).

    python3 gen_wa_helpers.py          # write the label and the modules
    python3 gen_wa_helpers.py --check  # exit 1 when something is out of date

The blocks that hold state (STATE_BLOCKS in isr_check.py) get no routines.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent))

from uc80 import isr_check  # noqa: E402

DIRS = ("rt", "lc")
# a label in the module of the area, and the lines that older versions wrote
OLD_BEGIN = "; ---- BEGIN work-area save helpers (gen_wa_helpers.py) ----"
OLD_END = "; ---- END work-area save helpers ----"
_ALIAS = re.compile(r"^[ \t]*PUBLIC[ \t]+__wa_\w+[ \t]*;!\n__wa_\w+:[ \t]*;!\n",
                    re.M)


def helper_name(path: Path) -> str:
    """The file name of the routines for the module ``path``."""
    return path.name.split("_", 1)[0] + "_wa_" + path.stem + ".mac"


def helper_text(block: str, size: int, modname: str) -> str:
    return "\n".join([
        f"; {modname} - GENERATED by gen_wa_helpers.py from the work area of "
        f"{block}   CONCAT-SKIP",
        "; Do not edit this file: run the script.  It saves and restores the",
        f"; work area of {block} for an interrupt function (docs/rom_hardware.md).",
        "\t.Z80",
        "",
        "\tCSEG",
        "",
        f"\tEXTRN\t__wa_{block}",
        f"\tPUBLIC\t__wasv_{block}",
        f"\tPUBLIC\t__wars_{block}",
        f"__wasv_{block}:",
        "\tPOP\tIY",
        f"\tLD\tHL,-{size}",
        "\tADD\tHL,SP",
        "\tLD\tSP,HL",
        "\tEX\tDE,HL",
        f"\tLD\tHL,__wa_{block}",
        f"\tLD\tBC,{size}",
        "\tLDIR",
        "\tJP\t(IY)",
        f"__wars_{block}:",
        "\tPOP\tIY",
        "\tLD\tHL,0",
        "\tADD\tHL,SP",
        f"\tLD\tDE,__wa_{block}",
        f"\tLD\tBC,{size}",
        "\tLDIR",
        "\tLD\tSP,HL",
        "\tJP\t(IY)",
        "",
        "\tEND",
        ""])


def strip_marks(text: str) -> str:
    """The module text without the label and without the old routines."""
    text = re.sub(re.escape(OLD_BEGIN) + r".*?" + re.escape(OLD_END)
                  + r"\n\n", "", text, flags=re.S)
    return _ALIAS.sub("", text)


def plan_file(path: Path):
    """(block, size) for a module with one work area, else None."""
    text = strip_marks(path.read_text())
    m = re.search(r"^\s*COMMON\s+/([^/]*)/", text, re.M)
    if not m or not m.group(1):
        return None
    block = m.group(1)
    if block in isr_check.STATE_BLOCKS:
        return None
    g = isr_check.Graph()
    isr_check._parse_unit(text, 0, g, is_lib=False, only_missing=False)
    if not g.layout0:
        return None
    sizes = [s for _l, s in g.layout0]
    if None in sizes or sum(sizes) == 0:
        return None
    return block, sum(sizes)


def marked_text(path: Path, plan) -> str:
    """The module text with the label of the area (or none for no plan)."""
    base = strip_marks(path.read_text())
    if not plan:
        return base
    block = plan[0]
    m = re.search(r"^[ \t]*COMMON[ \t]+/[^/]*/[^\n]*\n", base, re.M)
    return (base[:m.end()] + f"\tPUBLIC\t__wa_{block}\t;!\n"
            f"__wa_{block}:\t;!\n" + base[m.end():])


def update_file(path, count=None) -> list:
    """Write the label into the module ``path`` and its routines module next
    to it.  The generators of the library modules (gen_vm_modules.py,
    gen_c_modules.py) call this after they write a module.  Returns the
    names of the files that changed."""
    path = Path(path)
    plan = plan_file(path)
    if plan and count is not None and count.get(plan[0], 1) != 1:
        plan = None                   # two modules share the block name
    changed = []
    new = marked_text(path, plan)
    if new != path.read_text():
        path.write_text(new)
        changed.append(path.name)
    hp = path.with_name(helper_name(path))
    if plan:
        want = helper_text(plan[0], plan[1], hp.name)
        if not hp.exists() or hp.read_text() != want:
            hp.write_text(want)
            changed.append(hp.name)
    elif hp.exists():
        hp.unlink()
        changed.append(hp.name)
    return changed


def main(argv) -> int:
    check = "--check" in argv
    files = [p for d in DIRS for p in sorted((HERE / d).glob("*.mac"))
             if "_wa_" not in p.name]
    plans = {p: plan_file(p) for p in files}
    count = {}
    for pl in plans.values():
        if pl:
            count[pl[0]] = count.get(pl[0], 0) + 1
    stale = []
    for path in files:
        if check:
            pl = plans[path]
            if pl and count[pl[0]] != 1:
                pl = None
            hp = path.with_name(helper_name(path))
            if marked_text(path, pl) != path.read_text():
                stale.append(path.name)
            if pl and (not hp.exists() or hp.read_text()
                       != helper_text(pl[0], pl[1], hp.name)):
                stale.append(hp.name)
            if not pl and hp.exists():
                stale.append(hp.name)
        else:
            stale += update_file(path, count)
    if check:
        for n in stale:
            print("out of date:", n)
        return 1 if stale else 0
    print(f"{len(stale)} file(s) changed")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
