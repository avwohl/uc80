#!/usr/bin/env python3
"""Compile the C sources in csrc/ to library modules in lc/.

Each csrc/lc_NAME.c becomes lc/lc_NAME.mac.  The generated .mac files are
checked in, so a normal library build needs only um80 and ulib80.  Run this
script after you edit a file in csrc/ or after a code generator change that
you want in the library:

    python3 gen_c_modules.py            # all modules
    python3 gen_c_modules.py lc_strtol  # one module

Aliases: the comment "/* ALIAS: floor = floorf floorl */" in a C file adds the
entry points floorf and floorl at the address of floor.

Label rule: libc.mac is the concatenation of all modules, so every label
that is not PUBLIC must be unique over all modules.  This script gives each
compiler-made label (@WHILE1, ??AUTO, ...) the module name as a suffix, and a
C file must give its own static objects and functions names that start
with "<module>_" unless the name is already unique.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "csrc")
OUT = os.path.join(HERE, "lc")
REPO_SRC = os.path.dirname(os.path.dirname(HERE))

FLAGS = ["--no-whole-program", "--no-embed-runtime", "--no-embed-startup"]


def generate(name):
    c_file = os.path.join(SRC, name + ".c")
    mac = os.path.join(OUT, name + ".mac")
    tmp = mac + ".tmp"
    env = dict(os.environ, PYTHONPATH=REPO_SRC)
    r = subprocess.run([sys.executable, "-m", "uc80.main", c_file, "-o", tmp]
                       + FLAGS, capture_output=True, text=True, env=env)
    if r.returncode != 0:
        print(r.stdout + r.stderr)
        raise SystemExit(f"{name}: compile failed")
    text = open(tmp).read()
    os.remove(tmp)
    suffix = name[3:] if name.startswith("lc_") else name
    # Compiler labels: @NAMEn and ??AUTO get a module suffix.
    text = re.sub(r"(@[A-Za-z_]+\d+)\b", lambda m: m.group(1) + "_" + suffix, text)
    text = re.sub(r"\?\?AUTO\b", "??AUTO_" + suffix, text)
    # "/* ALIAS: name = other1 other2 */" gives the function NAME more entry
    # points at the same address (floor, floorf, floorl).
    src = open(c_file).read()
    for m in re.finditer(r"/\*\s*ALIAS:\s*(\w+)\s*=\s*([\w ]+?)\s*\*/", src):
        fn, others = m.group(1), m.group(2).split()
        label = f"_{fn}:"
        lines = text.split("\n")
        for i, ln in enumerate(lines):
            if ln.strip() == label:
                add = []
                for o in others:
                    add.append(f"\tPUBLIC\t_{o}")
                    add.append(f"_{o}:")
                lines[i + 1:i + 1] = add
                break
        else:
            raise SystemExit(f"{name}: ALIAS target {fn} not found")
        text = "\n".join(lines)
    # Static storage that starts as zero goes into a named COMMON block, so
    # that a ROM image does not hold its zero bytes (docs/rom.md).
    text = re.sub(r"; BSS - uninitialized static storage[^\n]*\n"
                  r"; the linker overlays[^\n]*\n\s*dseg\n",
                  f"; Static storage that starts as zero\n\tCOMMON\t/{name}/\n",
                  text, flags=re.I)
    # build_libs.py looks for upper-case directives when it joins the modules.
    text = re.sub(r"^(\s*)(public|extrn|cseg|dseg|end|\.z80)\b",
                  lambda m: m.group(1) + m.group(2).upper(), text,
                  flags=re.M)
    head = (f"; {name}.mac - GENERATED from csrc/{name}.c by gen_c_modules.py\n"
            "; Do not edit this file: edit the C file and run the script.\n")
    text = re.sub(r"^; C24 Compiler Output.*\n", "", text)
    open(mac, "w").write(head + text)
    print(f"  {name}.mac")


def main(argv):
    names = argv or sorted(f[:-2] for f in os.listdir(SRC) if f.endswith(".c"))
    for n in names:
        generate(n)


if __name__ == "__main__":
    main(sys.argv[1:])
