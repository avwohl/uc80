import argparse
import os
import random
import shutil
import subprocess
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

HERE = Path(__file__).resolve().parent
CPMEMU = os.environ.get("CPMEMU", str(Path.home() / "src/cpmemu/src/cpmemu"))

# ---------------------------------------------------------------- types
#
# name -> (C spelling, bits, signed).  Pointer types are separate.

SCALARS = {
    "uchar": ("unsigned char", 8, False),
    "schar": ("signed char", 8, True),
    "chr": ("char", 8, True),            # plain char: signed on both
    "ushort": ("unsigned short", 16, False),
    "short": ("short", 16, True),
    "I16": ("I16", 16, True),            # int on uc80
    "U16": ("U16", 16, False),           # unsigned int on uc80
    "L32": ("L32", 32, True),            # long on uc80
    "U32": ("U32", 32, False),
}
SCALAR_NAMES = list(SCALARS)
PTRS = {
    "pi": "I16 *",
    "pc": "unsigned char *",
    "ps": "struct S *",
}
RETS = ["uchar", "schar", "chr", "ushort", "short", "I16", "U16", "L32",
        "U32", "pi", "void"]
PARAM_KINDS = SCALAR_NAMES + ["pi", "pc", "ps"]
PARAM_WEIGHTS = [4, 3, 2, 3, 2, 5, 2, 3, 2, 3, 1, 2]


def ctype(t):
    if t in SCALARS:
        return SCALARS[t][0]
    if t in PTRS:
        return PTRS[t]
    return "void"


def is_ptr(t):
    return t in PTRS


class Func:
    def __init__(self, name, params, ret, static, pure, kind="plain"):
        self.name, self.params, self.ret = name, params, ret
        self.static, self.pure, self.kind = static, pure, kind
        self.depth_param = None       # index of the depth parameter

    def proto(self):
        ps = ", ".join(ctype(t) for t in self.params) or "void"
        return f"{'static ' if self.static else ''}{ctype(self.ret)} " \
               f"{self.name}({ps})"


HEADER = r"""/* generated by bench/ccfuzz.py: seed %(seed)d */
#include <stdio.h>
#include <stdarg.h>
#ifdef HOST
typedef short I16; typedef unsigned short U16;
typedef int L32; typedef unsigned int U32;
#else
typedef int I16; typedef unsigned int U16;
typedef long L32; typedef unsigned long U32;
#endif
struct S { signed char c; I16 i; L32 l; unsigned char u; };
unsigned char gc[16];
I16 gi[16];
L32 gl;
U32 gu;
struct S gs[4];
#define MIX(c, v) ((c) = ((c) * 31ul + (unsigned long)(U32)(v)) & 0xFFFFFFFFul)
"""


# ------------------------------------------------------------ generator

class Gen:
    def __init__(self, seed, trace=False):
        self.trace = trace
        self.r = random.Random(seed)
        self.seed = seed
        self.funcs: list[Func] = []
        self.out: list[str] = []
        self.tables: list[dict] = []     # function pointer tables
        self.nlocal = 0

    # ---- helpers
    def pick(self, seq):
        return self.r.choice(seq)

    def chance(self, p):
        return self.r.random() < p

    def const(self, t):
        bits, signed = SCALARS[t][1], SCALARS[t][2]
        edges = [0, 1, 2, 3, 7, 8, 15, 16, 100, 127, 128, 129, 255, 256, 257,
                 1000, 4095, 4096, 32767, 32768, 40000, 65535, 65536, 70000,
                 123456, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF]
        if self.chance(0.7):
            v = self.pick(edges)
        else:
            v = self.r.randrange(0, 1 << bits)
        if signed and self.chance(0.4):
            v = -v
        v &= (1 << bits) - 1
        if signed and v >> (bits - 1):
            v -= 1 << bits
        c = ctype(t)
        if bits == 32:
            return f"(({c})({v}L))" if signed else f"(({c})({v}UL))"
        return f"(({c})({v}))"

    # ---- expressions
    #
    # env: dict with
    #   vars: list of (name, type)      readable scalar / pointer variables
    #   pure: list of Func              functions callable in an expression
    # Every expression has the C type of the requested type t.

    def expr(self, t, env, depth):
        r = self.r
        if is_ptr(t):
            return self.ptr_expr(t, env, depth)
        if depth <= 0:
            return self.leaf(t, env)
        k = r.random()
        if k < 0.20:
            return self.leaf(t, env)
        if k < 0.52:
            c = self.call_expr(env, depth, want=t)
            if c is not None:
                return f"(({ctype(t)})({c}))"
        if k < 0.70:
            a = self.expr(self.pick(SCALAR_NAMES), env, depth - 1)
            b = self.expr(self.pick(SCALAR_NAMES), env, depth - 1)
            op = self.pick(["+", "-", "*", "&", "|", "^"])
            return (f"(({ctype(t)})((unsigned long)({a}) {op} "
                    f"(unsigned long)({b})))")
        if k < 0.76:
            a = self.expr(self.pick(SCALAR_NAMES), env, depth - 1)
            n = r.randrange(1, 8)
            if self.chance(0.5):
                return (f"(({ctype(t)})((unsigned long)(U32)({a}) >> {n}))")
            return (f"(({ctype(t)})((unsigned long)(U32)({a}) << {n}))")
        if k < 0.80:
            a = self.expr(self.pick(SCALAR_NAMES), env, depth - 1)
            if self.chance(0.5):
                return f"(({ctype(t)})(-(unsigned long)({a})))"
            return f"(({ctype(t)})(~(unsigned long)({a})))"
        if k < 0.84:
            a = self.expr(self.pick(SCALAR_NAMES), env, depth - 1)
            m = r.randrange(1, 200)
            op = self.pick(["/", "%"])
            return f"(({ctype(t)})((U32)({a}) {op} {m}u))"
        if k < 0.92:
            c = self.cond(env, depth - 1)
            return (f"(({c}) ? ({ctype(t)})({self.expr(t, env, depth - 1)}) "
                    f": ({ctype(t)})({self.expr(t, env, depth - 1)}))")
        c = self.cond(env, depth - 1)
        return f"(({ctype(t)})({c}))"

    def leaf(self, t, env):
        r = self.r
        k = r.random()
        cands = [(n, vt) for n, vt in env["vars"] if not is_ptr(vt)]
        if k < 0.35 and cands:
            n, vt = self.pick(cands)
            return f"(({ctype(t)}){n})"
        ptrs = [(n, vt) for n, vt in env["vars"] if is_ptr(vt)]
        if k < 0.55 and ptrs:
            n, vt = self.pick(ptrs)
            return f"(({ctype(t)}){self.deref(n, vt)})"
        pp = [f for f in env["pure"] if f.ret == "pi"]
        if 0.65 <= k < 0.72 and pp:
            f = self.pick(pp)
            return (f"(({ctype(t)}){self.call_text(f, env, 1)}"
                    f"[{r.randrange(3)}])")
        if k < 0.65:
            g = self.pick(["gc[%d]" % r.randrange(16), "gi[%d]" % r.randrange(16),
                           "gl", "gu", "gs[%d].i" % r.randrange(4),
                           "gs[%d].c" % r.randrange(4), "gs[%d].l" % r.randrange(4)])
            return f"(({ctype(t)}){g})"
        return self.const(t)

    def deref(self, n, vt):
        r = self.r
        if vt == "pi":
            return f"{n}[{r.randrange(3)}]"
        if vt == "pc":
            return f"{n}[{r.randrange(3)}]"
        f = self.pick(["c", "i", "l", "u"])
        return f"{n}->{f}"

    def ptr_expr(self, t, env, depth):
        r = self.r
        cands = [n for n, vt in env["vars"] if vt == t]
        if cands and self.chance(0.5):
            return self.pick(cands)
        if t == "pi":
            return f"(gi + {r.randrange(8)})" if depth <= 0 or self.chance(0.5) \
                else f"(gi + (({self.expr('uchar', env, depth - 1)}) & 7))"
        if t == "pc":
            return f"(gc + {r.randrange(8)})" if depth <= 0 or self.chance(0.5) \
                else f"(gc + (({self.expr('uchar', env, depth - 1)}) & 7))"
        return f"(gs + {r.randrange(3)})" if depth <= 0 or self.chance(0.5) \
            else f"(gs + (({self.expr('uchar', env, depth - 1)}) & 3))"

    def cond(self, env, depth):
        r = self.r
        k = r.random()
        if depth <= 0 or k < 0.5:
            t = self.pick(["uchar", "schar", "ushort", "I16", "U16", "L32", "U32"])
            a = self.expr(t, env, depth - 1)
            b = self.expr(t, env, depth - 1)
            op = self.pick(["<", "<=", ">", ">=", "==", "!="])
            return f"(({ctype(t)})({a}) {op} ({ctype(t)})({b}))"
        if k < 0.65:
            return f"(!{self.cond(env, depth - 1)})"
        if k < 0.85:
            op = self.pick(["&&", "||"])
            return f"({self.cond(env, depth - 1)} {op} {self.cond(env, depth - 1)})"
        t = self.pick(SCALAR_NAMES)
        return f"(({self.expr(t, env, depth - 1)}) != 0)"

    def call_expr(self, env, depth, want=None):
        """A call of a pure function in an expression, or None."""
        pure = [f for f in env["pure"] if f.ret != "void" and not is_ptr(f.ret)]
        if want is not None and self.chance(0.6):
            same = [f for f in pure if f.ret == want]
            pure = same or pure
        if not pure:
            return None
        k = self.r.random()
        if k < 0.10 and self.tables:
            tb = self.pick(self.tables)
            idx = self.expr("uchar", env, depth - 1)
            args = ", ".join(self.arg(t, env, depth - 1) for t in tb["params"])
            return f"{tb['name']}[({idx}) & {tb['n'] - 1}]({args})"
        if k < 0.17:
            return self.variadic_call(env, depth)
        f = self.pick(pure)
        return self.call_text(f, env, depth)

    def variadic_call(self, env, depth):
        n = self.r.randrange(1, 5)
        if self.chance(0.5):
            args = ", ".join(f"(I16)({self.expr('I16', env, depth - 1)})"
                             for _ in range(n))
            return f"vsum({n}, {args})"
        args = ", ".join(f"(L32)({self.expr('L32', env, depth - 1)})"
                         for _ in range(n))
        return f"lsum({n}, {args})"

    def arg(self, t, env, depth):
        return self.expr(t, env, depth)

    def call_text(self, f, env, depth):
        args = []
        for i, t in enumerate(f.params):
            if f.kind in ("rec", "mut") and i == f.depth_param:
                args.append(f"(unsigned char)(({self.expr('uchar', env, 0)}) & {self.pick([1, 3, 3])})")
            else:
                args.append(self.arg(t, env, depth - 1))
        return f"{f.name}({', '.join(args)})"

    # ---- statements

    def new_local(self, env, t=None):
        t = t or self.pick(SCALAR_NAMES)
        self.nlocal += 1
        n = f"v{self.nlocal}"
        return n, t

    def stmts(self, env, depth, n, in_loop=False, writable=None):
        lines = []
        for _ in range(n):
            lines.extend(self.stmt(env, depth, in_loop, writable))
        return lines

    def stmt(self, env, depth, in_loop, writable):
        r = self.r
        k = r.random()
        w = writable if writable is not None else []
        if k < 0.22 and w:
            n, t = self.pick(w)
            return [f"{n} = {self.expr(t, env, 3)};"]
        if k < 0.34 and w:
            n, t = self.pick(w)
            op = self.pick(["+", "-", "*", "&", "|", "^"])
            return [f"{n} = ({ctype(t)})((unsigned long){n} {op} "
                    f"(unsigned long)({self.expr(self.pick(SCALAR_NAMES), env, 2)}));"]
        if k < 0.38 and w:
            return self.addr_stmt(env, w)
        if k < 0.46 and depth > 0:
            c = self.cond(env, 2)
            a = self.stmts(env, depth - 1, r.randrange(1, 3), in_loop, w)
            if self.chance(0.5):
                b = self.stmts(env, depth - 1, r.randrange(1, 3), in_loop, w)
                return [f"if {c} {{"] + a + ["} else {"] + b + ["}"]
            return [f"if {c} {{"] + a + ["}"]
        if k < 0.56 and depth > 0:
            self.nlocal += 1
            iv = f"i{self.nlocal}"
            body = self.stmts(env, depth - 1, r.randrange(1, 3), True, w)
            kmax = r.randrange(1, 5)
            if self.chance(0.7):
                return [f"{{ unsigned char {iv};",
                        f"for ({iv} = 0; {iv} < {kmax}; {iv}++) {{"] + body + ["} }"]
            return [f"{{ unsigned char {iv} = {kmax};",
                    f"while ({iv}--) {{"] + body + ["} }"]
        if k < 0.64:
            # array and struct stores (pure expressions on both sides)
            tgt = self.pick([
                f"gc[({self.expr('uchar', env, 1)}) & 15] = (unsigned char)({self.expr('uchar', env, 2)});",
                f"gi[({self.expr('uchar', env, 1)}) & 15] = (I16)({self.expr('I16', env, 2)});",
                f"gs[({self.expr('uchar', env, 1)}) & 3].i = (I16)({self.expr('I16', env, 2)});",
                f"gs[({self.expr('uchar', env, 1)}) & 3].l = (L32)({self.expr('L32', env, 2)});",
                f"gl = (L32)({self.expr('L32', env, 2)});",
                f"gu = (U32)({self.expr('U32', env, 2)});"])
            return [tgt]
        if k < 0.72:
            pw = [(n, t) for n, t in env["vars"] if is_ptr(t)]
            if pw:
                n, t = self.pick(pw)
                if t == "pi":
                    return [f"{n}[{r.randrange(3)}] = (I16)({self.expr('I16', env, 2)});"]
                if t == "pc":
                    return [f"{n}[{r.randrange(3)}] = (unsigned char)({self.expr('uchar', env, 2)});"]
                return [f"{n}->i = (I16)({self.expr('I16', env, 2)});"]
        # impure call as a statement
        imp = [f for f in env.get("impure", [])]
        if imp:
            f = self.pick(imp)
            call = self.call_text(f, env, 3)
            if f.ret != "void" and not is_ptr(f.ret) and w:
                n, t = self.pick(w)
                return [f"{n} = ({ctype(t)})({call});"]
            return [f"{call};"]
        if w:
            n, t = self.pick(w)
            return [f"{n} = {self.expr(t, env, 3)};"]
        return [";"]

    # ---- functions

    def signature(self):
        np_ = self.pick([0, 1, 1, 2, 2, 2, 3, 3, 4])
        params = self.r.choices(PARAM_KINDS, PARAM_WEIGHTS, k=np_)
        ret = self.pick(RETS)
        return params, ret

    def ret_stmt(self, f, env):
        if f.ret == "void":
            return []
        return [f"return {self.expr(f.ret, env, 3)};"]

    def make_function(self, idx, pure_funcs, impure_funcs, force=None):
        r = self.r
        name = f"f{idx}"
        if force:
            params, ret = force
        else:
            params, ret = self.signature()
        # pure: only reads state.  impure: stores to globals and calls impure
        # functions in statements.
        pure = self.chance(0.55) and ret != "void"
        static = self.chance(0.5)
        f = Func(name, params, ret, static, pure)
        env = {"vars": [], "pure": list(pure_funcs),
               "impure": [] if pure else list(impure_funcs)}
        body = []
        pnames = []
        for i, t in enumerate(params):
            n = f"p{i}"
            pnames.append(n)
            env["vars"].append((n, t))
        # the impure function may store through pointer parameters and
        # globals; a pure function writes only its own locals
        locs = []
        for _ in range(r.randrange(0, 4)):
            n, t = self.new_local(env)
            init = self.expr(t, env, 2)
            body.append(f"{ctype(t)} {n} = {init};")
            env["vars"].append((n, t))
            locs.append((n, t))
        writable = list(locs)
        if self.chance(0.5):
            # a parameter that is assigned: legal C and it tests the spill
            for i, t in enumerate(params):
                if not is_ptr(t) and self.chance(0.45):
                    writable.append((pnames[i], t))
        if not pure:
            pass
        else:
            # a pure function must not store to globals or through pointers
            pass
        body += self.pure_or_impure_stmts(f, env, writable, pure)
        if self.chance(0.25) and ret != "void":
            c = self.cond(env, 2)
            body.append(f"if {c} return {self.expr(ret, env, 2)};")
        body += self.ret_stmt(f, env)
        self.emit_func(f, pnames, body)
        return f

    def pure_or_impure_stmts(self, f, env, writable, pure):
        n = self.r.randrange(0, 4)
        if pure:
            saved = env["vars"]
            # statements for a pure function: locals only.  stmt() writes to
            # globals in the 0.56..0.72 band, so use a restricted version.
            lines = []
            for _ in range(n):
                lines.extend(self.pure_stmt(env, 2, writable))
            return lines
        return self.stmts(env, 2, n, False, writable)

    def pure_stmt(self, env, depth, writable):
        r = self.r
        k = r.random()
        w = writable
        if k < 0.30 and w:
            n, t = self.pick(w)
            return [f"{n} = {self.expr(t, env, 3)};"]
        if k < 0.50 and w:
            n, t = self.pick(w)
            op = self.pick(["+", "-", "*", "&", "|", "^"])
            return [f"{n} = ({ctype(t)})((unsigned long){n} {op} "
                    f"(unsigned long)({self.expr(self.pick(SCALAR_NAMES), env, 2)}));"]
        if k < 0.56 and w:
            return self.addr_stmt(env, w)
        if k < 0.72 and depth > 0:
            c = self.cond(env, 2)
            a = self.pure_block(env, depth - 1, w)
            if self.chance(0.5):
                return [f"if {c} {{"] + a + ["} else {"] + self.pure_block(env, depth - 1, w) + ["}"]
            return [f"if {c} {{"] + a + ["}"]
        if depth > 0:
            self.nlocal += 1
            iv = f"i{self.nlocal}"
            body = self.pure_block(env, depth - 1, w)
            return [f"{{ unsigned char {iv};",
                    f"for ({iv} = 0; {iv} < {r.randrange(1, 5)}; {iv}++) {{"] + body + ["} }"]
        return [";"]

    def addr_stmt(self, env, w):
        """Take the address of a local or a parameter and store through it:
        the slot of a register parameter must then be real memory."""
        n, t = self.pick(w)
        self.nlocal += 1
        q = f"q{self.nlocal}"
        return [f"{{ {ctype(t)} *{q} = &{n}; "
                f"*{q} = ({ctype(t)})({self.expr(t, env, 2)}); "
                f"{n} = ({ctype(t)})((unsigned long)*{q} + 1ul); }}"]

    def pure_block(self, env, depth, w):
        lines = []
        for _ in range(self.r.randrange(1, 3)):
            lines.extend(self.pure_stmt(env, depth, w))
        return lines

    def emit_func(self, f, pnames, body):
        ps = ", ".join(f"{ctype(t)} {n}" for t, n in zip(f.params, pnames)) \
            or "void"
        self.out.append(f"{'static ' if f.static else ''}{ctype(f.ret)} "
                        f"{f.name}({ps})")
        self.out.append("{")
        self.out.extend("  " + l for l in body)
        self.out.append("}")
        self.out.append("")

    def make_recursive(self, idx, pure_funcs):
        """f(d, ...) with a depth parameter at a random position."""
        r = self.r
        params, ret = self.signature()
        if ret == "void" or is_ptr(ret):
            ret = self.pick(["I16", "L32", "uchar", "U16"])
        pos = r.randrange(len(params) + 1)
        params.insert(pos, "uchar")
        params = params[:5]
        if pos >= len(params):
            pos = len(params) - 1
            params[pos] = "uchar"
        f = Func(f"r{idx}", params, ret, self.chance(0.5), True, "rec")
        f.depth_param = pos
        pn = [f"p{i}" for i in range(len(params))]
        env = {"vars": [(n, t) for n, t in zip(pn, params)],
               "pure": list(pure_funcs), "impure": []}
        dn = pn[pos]
        selfcalls = []
        for _ in range(self.pick([1, 1, 2])):
            args = []
            for i, t in enumerate(params):
                if i == pos:
                    args.append(f"(unsigned char)({dn} - 1)")
                else:
                    args.append(self.expr(t, env, 2))
            selfcalls.append(f"(unsigned long){f.name}({', '.join(args)})")
        base = self.expr(ret, env, 2)
        mix = self.expr(ret, env, 2)
        body = [f"if ({dn} == 0) return {base};"]
        use = " + ".join(selfcalls)
        body.append(f"return ({ctype(ret)})((unsigned long)({mix}) + {use});")
        self.emit_func(f, pn, body)
        return f

    def make_mutual(self, idx, pure_funcs):
        r = self.r
        ret = self.pick(["I16", "L32", "uchar", "U16"])
        mk = []
        for nm in ("ma", "mb"):
            params, _ = self.signature()
            pos = r.randrange(len(params) + 1)
            params.insert(pos, "uchar")
            params = params[:4]
            if pos >= len(params):
                pos = len(params) - 1
                params[pos] = "uchar"
            mk.append((f"{nm}{idx}", params, pos))
        # both take the same list of types so each can call the other with
        # arbitrary arguments of the callee's types
        fa = Func(mk[0][0], mk[0][1], ret, self.chance(0.5), True, "mut")
        fb = Func(mk[1][0], mk[1][1], ret, self.chance(0.5), True, "mut")
        fa.depth_param, fb.depth_param = mk[0][2], mk[1][2]
        # forward declaration of fb
        self.out.append(fb.proto() + ";")
        for me, other in ((fa, fb), (fb, fa)):
            pn = [f"p{i}" for i in range(len(me.params))]
            env = {"vars": [(n, t) for n, t in zip(pn, me.params)],
                   "pure": list(pure_funcs), "impure": []}
            dn = pn[me.depth_param]
            args = []
            for i, t in enumerate(other.params):
                if i == other.depth_param:
                    args.append(f"(unsigned char)({dn} - 1)")
                else:
                    args.append(self.expr(t, env, 2))
            body = [f"if ({dn} == 0) return {self.expr(ret, env, 2)};",
                    f"return ({ctype(ret)})((unsigned long)({self.expr(ret, env, 2)}) + "
                    f"(unsigned long){other.name}({', '.join(args)}));"]
            self.emit_func(me, pn, body)
        return [fa, fb]

    def make_table(self, idx, pure_funcs):
        """Functions with one signature, and a table of pointers to them."""
        r = self.r
        params, ret = self.signature()
        if ret == "void" or is_ptr(ret):
            ret = "I16"
        params = [p for p in params if not is_ptr(p)][:3] or ["I16"]
        n = self.pick([2, 4])
        members = []
        for j in range(n):
            f = Func(f"t{idx}_{j}", list(params), ret, self.chance(0.5), True, "tab")
            pn = [f"p{i}" for i in range(len(params))]
            env = {"vars": [(nm, t) for nm, t in zip(pn, params)],
                   "pure": list(pure_funcs), "impure": []}
            body = []
            if self.chance(0.5):
                body.append(f"if {self.cond(env, 2)} return {self.expr(ret, env, 2)};")
            body.append(f"return {self.expr(ret, env, 3)};")
            self.emit_func(f, pn, body)
            members.append(f)
        tname = f"tab{idx}"
        ptype = f"{ctype(ret)} (*{tname}[{n}])({', '.join(ctype(p) for p in params)})"
        self.out.append(f"{ptype} = {{ {', '.join(m.name for m in members)} }};")
        self.out.append("")
        self.tables.append({"name": tname, "params": params, "ret": ret, "n": n})
        return members

    def program(self):
        r = self.r
        o = self.out
        o.append(HEADER % {"seed": self.seed})
        o.append("""I16 vsum(int n, ...)
{
  va_list ap; I16 s = 0; int i;
  va_start(ap, n);
  for (i = 0; i < n; i++) s = (I16)((unsigned long)s * 3ul + (unsigned long)va_arg(ap, int));
  va_end(ap);
  return s;
}

L32 lsum(int n, ...)
{
  va_list ap; L32 s = 0; int i;
  va_start(ap, n);
  for (i = 0; i < n; i++) s = (L32)((unsigned long)s * 3ul + (unsigned long)va_arg(ap, L32));
  va_end(ap);
  return s;
}
""")
        pure_funcs: list[Func] = []
        impure_funcs: list[Func] = []
        nfun = r.randrange(7, 15)
        idx = 0
        while len(pure_funcs) + len(impure_funcs) < nfun:
            k = r.random()
            idx += 1
            if k < 0.12:
                pure_funcs.append(self.make_recursive(idx, pure_funcs))
            elif k < 0.18:
                pure_funcs.extend(self.make_mutual(idx, pure_funcs))
            elif k < 0.26:
                self.make_table(idx, pure_funcs)
                # members are callable by name too (they keep the stack
                # convention: the address is taken)
                pure_funcs.extend(self.funcs_of_last_table(idx))
            else:
                f = self.make_function(idx, pure_funcs, impure_funcs)
                (pure_funcs if f.pure else impure_funcs).append(f)
        self.pure_funcs, self.impure_funcs = pure_funcs, impure_funcs
        # main
        o.append("int main(void)")
        o.append("{")
        o.append("  unsigned long chk = 7;")
        env = {"vars": [], "pure": pure_funcs, "impure": impure_funcs}
        body = []
        for j in range(r.randrange(25, 50)):
            k = r.random()
            if k < 0.6:
                f = self.pick(pure_funcs + impure_funcs)
                if f.pure and f.ret != "void":
                    if is_ptr(f.ret):
                        continue
                    body.append(f"MIX(chk, {self.call_text(f, env, 3)});")
                elif f.pure:
                    body.append(f"{self.call_text(f, env, 3)};")
                else:
                    if f.ret == "void" or is_ptr(f.ret):
                        body.append(f"{self.call_text(f, env, 3)};")
                    else:
                        body.append(f"MIX(chk, {self.call_text(f, env, 3)});")
            elif k < 0.8:
                c = self.call_expr(env, 3)
                if c:
                    body.append(f"MIX(chk, {c});")
            else:
                body.append("MIX(chk, gl); MIX(chk, gu); "
                            "{ int q; for (q = 0; q < 16; q++) { MIX(chk, gc[q]); MIX(chk, gi[q]); } "
                            "for (q = 0; q < 4; q++) { MIX(chk, gs[q].c); MIX(chk, gs[q].i); "
                            "MIX(chk, gs[q].l); MIX(chk, gs[q].u); } }")
            if self.trace or j % 6 == 5:
                body.append('printf("%lu\\n", chk);')
        body.append('printf("%lu\\n", chk);')
        o.extend("  " + l for l in body)
        o.append("  return 0;")
        o.append("}")
        return "\n".join(o) + "\n"

    def funcs_of_last_table(self, idx):
        # re-create Func records for the table members (they are pure)
        out = []
        tb = self.tables[-1]
        for j in range(tb["n"]):
            out.append(Func(f"t{idx}_{j}", list(tb["params"]), tb["ret"], False, True, "tab"))
        # static is irrelevant to callers
        return out


def make_program(seed, trace=False):
    g = Gen(seed, trace)
    return g.program()


# --------------------------------------------------------------- running

def sh(cmd, cwd, timeout=300, env=None):
    try:
        p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True,
                           timeout=timeout, env=env, errors="replace")
    except subprocess.TimeoutExpired:
        return 124, "timeout: " + " ".join(cmd)
    return p.returncode, p.stdout + p.stderr


def run_com(com: Path, timeout=60):
    try:
        p = subprocess.run([CPMEMU, str(com)], capture_output=True, text=True,
                           timeout=timeout, errors="replace", cwd=com.parent,
                           stdin=subprocess.DEVNULL)
    except subprocess.TimeoutExpired:
        return None
    return p.stdout.replace("\r", "")


VARIANTS = [[], [], ["--no-inlining"], ["--no-shared-storage"],
            ["--no-inlining"], ["-O0"], ["--no-const-propagation"],
            ["--no-inlining", "--no-shared-storage"], ["--isr-safe"],
            ["--no-ast-optimize"], ["--no-inlining", "-O0"]]


def uc80_build(src: Path, work: Path, flags):
    lib = Path(sh(["uc80", "--print-lib-dir"], work)[1].strip())
    for cmd in (["uc80", str(src), "-o", "prog.mac"] + flags,
                ["um80", "prog.mac", "-o", "prog.rel"],
                ["ul80", "prog.rel", str(lib / "libc.lib"),
                 str(lib / "runtime.lib"), "-o", "prog.com"]):
        rc, out = sh(cmd, work)
        if rc != 0:
            return None, out
    return work / "prog.com", ""


def one(seed, opts):
    work = Path(opts.work) / f"s{seed}"
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    text = make_program(seed)
    src = work / "prog.c"
    src.write_text(text)
    rc, out = sh(["cc", "-O1", "-w", "-fsigned-char", "-DHOST", "prog.c",
                  "-o", "host"], work)
    if rc != 0:
        status = "HOST-FAIL"
        note = out[:400]
    else:
        rc, hout = sh(["./host"], work, 30)
        if rc != 0:
            status, note = "HOST-FAIL", f"host exit {rc}"
        else:
            flags = list(VARIANTS[seed % len(VARIANTS)]) + opts.flags.split()
            com, log = uc80_build(src, work, flags)
            if com is None:
                status, note = "BUILD-FAIL", log[-600:]
            else:
                got = run_com(com)
                if got is None:
                    status, note = "HANG", ""
                elif got.strip() == hout.strip():
                    status, note = "PASS", ""
                else:
                    status = "WRONG"
                    note = f"flags={flags}"
                    # does the stack convention fix it?
                    com2, _ = uc80_build(src, work, flags + ["--no-register-cc"])
                    if com2 is not None:
                        g2 = run_com(com2)
                        if g2 is not None and g2.strip() == hout.strip():
                            status = "REG-WRONG"
                    gl = got.strip().splitlines()
                    hl = hout.strip().splitlines()
                    for i in range(max(len(gl), len(hl))):
                        if i >= len(gl) or i >= len(hl) or gl[i] != hl[i]:
                            note += f" first diff at output line {i + 1}"
                            break
    if status != "PASS" and opts.keep:
        keep = Path(opts.keep) / f"s{seed}"
        keep.mkdir(parents=True, exist_ok=True)
        shutil.copy(src, keep / "prog.c")
        (keep / "note.txt").write_text(f"{status} {note}\n")
    if not opts.keep_work:
        shutil.rmtree(work, ignore_errors=True)
    return seed, status, note


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--count", type=int, default=100)
    ap.add_argument("--seed", type=int, default=1, help="first seed")
    ap.add_argument("-j", type=int, default=4)
    ap.add_argument("--work", default=str(HERE / "_work" / "ccfuzz"))
    ap.add_argument("--keep", help="directory for failing programs")
    ap.add_argument("--keep-work", action="store_true")
    ap.add_argument("--flags", default="", help="extra uc80 flags")
    ap.add_argument("--print", type=int, metavar="SEED")
    ap.add_argument("--trace", action="store_true",
                    help="with --print: print the checksum after each statement")
    opts = ap.parse_args()
    opts.work = str(Path(opts.work).resolve())
    if opts.keep:
        opts.keep = str(Path(opts.keep).resolve())
    if opts.print is not None:
        sys.stdout.write(make_program(opts.print, opts.trace))
        return 0
    Path(opts.work).mkdir(parents=True, exist_ok=True)
    seeds = range(opts.seed, opts.seed + opts.count)
    counts: dict[str, int] = {}
    t0 = time.time()
    with ProcessPoolExecutor(opts.j) as ex:
        futs = [ex.submit(one, s, opts) for s in seeds]
        for n, fu in enumerate(as_completed(futs), 1):
            seed, status, note = fu.result()
            counts[status] = counts.get(status, 0) + 1
            if status != "PASS":
                print(f"seed {seed}: {status} {note}", flush=True)
            if n % 100 == 0:
                print(f"  {n}/{opts.count} {counts} {time.time() - t0:.0f}s",
                      flush=True)
    print(f"{opts.count} programs: {counts} in {time.time() - t0:.0f}s")
    bad = sum(v for k, v in counts.items() if k not in ("PASS", "HOST-FAIL"))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
