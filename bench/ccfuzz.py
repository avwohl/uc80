#!/usr/bin/env python3
"""Calling-convention fuzzer: random call-heavy C programs, uc80 against the host.

    python3 bench/ccfuzz.py --count 2000 -j 8
    python3 bench/ccfuzz.py --count 200 --seed 5000 --keep /tmp/ccf
    python3 bench/ccfuzz.py --print 17            # show program 17

Each program has many small functions with random signatures: 0 to 4
parameters of type char, short, int, long, unsigned types, a pointer to an
int array, a pointer to a struct; results of type char, int, long, a
pointer, or void.  The functions call each other, with calls as arguments of
calls, calls in conditions, loops and ?: expressions, self recursion (the
depth is a parameter at a random position), mutual recursion, calls through
tables of function pointers, variadic helpers, and static and non-static
definitions.  The aim is the register calling convention
(docs/calling_convention.md): a function that is only called by name
takes its first two parameters in registers; a function whose address is
taken, a variadic function and a library function keep the stack convention.
Calls go both ways between the two conventions.

The program is the same text for the host and for uc80.  `int` of uc80 is
`I16` and `long` is `L32`; on the host these are `short` and `int`.  The
program never has undefined behaviour: arithmetic is done in unsigned long
and cut to the type of the result, and an expression with a side effect
(a call that writes a global) is only ever a whole statement, with
arguments that have no side effects, so the order of evaluation does not
change the result.  The checksum of every result is printed.

Statuses: PASS, WRONG (output differs; the status is REG-WRONG when the
same program is right with --no-register-cc, which names the convention),
BUILD-FAIL, HOST-FAIL, HANG.
"""

